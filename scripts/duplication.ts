/**
 * Copy-paste check (`npm run duplication`, also run by `npm run hygiene`):
 * AGENTS.md §10, "one path per capability". Runs jscpd
 * over the application code and the tests and fails when it finds a clone,
 * listing each pair so it can be consolidated into a shared component,
 * rune module, helper or service.
 *
 * The thresholds catch real copy-paste (a repeated query, mapper, form or
 * handler) without flagging the small repeated shapes every file has.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import { z } from 'zod';

interface Scan {
	readonly name: string;
	readonly paths: readonly string[];
	readonly minLines: number;
	readonly minTokens: number;
}

const SCANS: readonly Scan[] = [
	{ name: 'application code', paths: ['src', 'scripts'], minLines: 10, minTokens: 100 },
	// Tests repeat arrange steps on purpose for readability, so only longer
	// copies count.
	{ name: 'tests', paths: ['tests'], minLines: 15, minTokens: 120 }
];

const IGNORE = [
	'**/node_modules/**',
	// Generated by drizzle-kit.
	'src/lib/server/database/migrations/**',
	// Drizzle tables spell every column out per table, so shared column sets
	// are intentionally not factored out.
	'src/lib/server/database/schema/**'
];

/**
 * Scoped `<style>` blocks (AGENTS.md §4) may repeat the same few rules in
 * several components; shared style modules are forbidden, so CSS clones are
 * not reported. Repeated markup and script still are.
 */
const IGNORED_FORMATS = new Set(['css']);

const Location = z.object({ name: z.string(), start: z.number(), end: z.number() });
const Report = z.object({
	duplicates: z.array(
		z.object({
			format: z.string(),
			lines: z.number(),
			tokens: z.number(),
			firstFile: Location,
			secondFile: Location
		})
	)
});
type Clone = z.infer<typeof Report>['duplicates'][number];

function runScan(scan: Scan, outputDir: string): Clone[] {
	const args = [
		...scan.paths,
		'--format',
		'typescript,svelte',
		'--min-lines',
		String(scan.minLines),
		'--min-tokens',
		String(scan.minTokens),
		'--ignore',
		IGNORE.join(','),
		'--reporters',
		'json',
		'--output',
		outputDir,
		'--absolute',
		'--silent',
		'--no-tips'
	];
	execFileSync('node_modules/.bin/jscpd', args, { stdio: ['ignore', 'ignore', 'inherit'] });
	const report = Report.parse(
		JSON.parse(readFileSync(join(outputDir, 'jscpd-report.json'), 'utf8'))
	);
	return report.duplicates.filter((clone) => !IGNORED_FORMATS.has(clone.format));
}

function where(file: z.infer<typeof Location>): string {
	return `${relative(process.cwd(), file.name)}:${String(file.start)}-${String(file.end)}`;
}

function main(): void {
	const outputRoot = mkdtempSync(join(tmpdir(), 'jscpd-'));
	let total = 0;
	try {
		for (const [index, scan] of SCANS.entries()) {
			const clones = runScan(scan, join(outputRoot, String(index)));
			total += clones.length;
			for (const clone of clones) {
				console.error(
					`duplicate-code: ${where(clone.firstFile)} <> ${where(clone.secondFile)} (${String(clone.lines)} lines, ${String(clone.tokens)} tokens)`
				);
			}
			console.log(
				`${scan.name}: ${String(clones.length)} clone(s) of ${String(scan.minLines)}+ lines / ${String(scan.minTokens)}+ tokens`
			);
		}
	} finally {
		rmSync(outputRoot, { recursive: true, force: true });
	}
	if (total > 0) {
		console.error(
			`\n${String(total)} duplicated block(s). Consolidate each into one shared component, rune module, helper or service (AGENTS.md §10).`
		);
		process.exit(1);
	}
	console.log('No duplicated code.');
}

main();
